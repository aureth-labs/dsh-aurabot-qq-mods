/** 归一化档位：非法值回落到 2 */
export function normLevel(v) {
  const n = Number(v)
  return n === 1 || n === 2 || n === 3 ? n : 2
}

/** 生成某档语料文件的模板文本 */
export function corpusTemplate(level) {
  const t = TIERS[normLevel(level)]
  return [
    `# 毒舌模式2 · ${t.name}（${normLevel(level)}档）风格语料：每行一句；# 开头与空行忽略。`,
    '# 模块每次发言随机抽几句当风格示例，让回复贴合当前聊天，不是随机照抄。',
    '# 改完保存即可，无需重启；删掉本文件会在下次触发时重新生成默认语料。',
    ...t.lines,
  ].join('\n') + '\n'
}
