import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { REMINDER_PROPERTIES } from '../lib/companion/aurabot-tools.mjs';

test('actual reminder panel selects once date/time and preserves periodic choices', async () => {
  const slots = [], calls = [], notices = []; let cursor = 0;
  const React = { useState(initial) { const i = cursor++; if (!(i in slots)) slots[i] = initial;
    return [slots[i], value => { slots[i] = typeof value === 'function' ? value(slots[i]) : value; }]; }, useEffect() {}, useRef() { return { current: null }; } };
  const h = (type, props, ...children) => ({ type, props: props || {}, children: children.flat(Infinity) });
  const ui = new Proxy({}, { get: (_, key) => key });
  const call = async (path, body) => { calls.push({ path, body });
    if (path === '/status') throw Error('synthetic refresh failure');
    if (path === '/reminders/create') return { ok: true, message: '提醒已保存' };
    return { ok: false }; };
  const Panel = new Function('React','h','ui','call',await readFile(new URL('../panel.js',import.meta.url),'utf8'))(React,h,ui,call);
  let nodes;
  const render = () => { cursor = 0; nodes = []; const walk = x => { if (!x || typeof x !== 'object') return; nodes.push(x); x.children?.forEach(walk); }; walk(Panel({ toast: text => notices.push(text) })); };
  const label = text => nodes.find(n => n.props['aria-label'] === text);
  const button = text => nodes.find(n => n.type === 'Btn' && n.children.includes(text));
  const change = (name, value) => { label(name).props.onChange({ target: { value } }); render(); };
  render();
  change('提醒周期', 'monthly');
  change('每月提醒日期', '31');
  change('提醒类型', 'once');
  assert.equal(label('提醒周期'), undefined);
  assert.equal(label('每月提醒日期'), undefined);
  assert.equal(label('一次提醒日期').props.type, 'date');
  change('提醒提示词', '隔离提醒');
  assert.equal(button('保存一次提醒').props.disabled, true);
  change('一次提醒日期', '2027-02-01'); change('提醒时间', '14:30');
  assert.equal(button('保存一次提醒').props.disabled, false);
  await button('保存一次提醒').props.onClick(); render();
  assert.equal(label('提醒提示词').props.value, '', 'successful save clears draft even when status refresh fails');
  assert.ok(notices.some(text => text.includes('刷新')));
  assert.deepEqual(calls.find(c => c.path === '/reminders/create').body, { text: '隔离提醒', schedule: { frequency: 'once', date: '2027-02-01', time: '14:30' } });
  change('提醒类型', 'periodic');
  assert.equal(label('一次提醒日期'), undefined);
  assert.equal(label('提醒周期').props.value, 'monthly');
  assert.equal(label('每月提醒日期').props.value, 31);
  change('提醒提示词', '隔离提醒');
  await button('保存周期提醒').props.onClick();
  assert.deepEqual(calls.filter(c => c.path === '/reminders/create').at(-1).body.schedule, { frequency: 'monthly', time: '14:30', monthDay: 31 });
  assert.ok(REMINDER_PROPERTIES.schedule.properties.frequency.enum.includes('once'));
  assert.equal(REMINDER_PROPERTIES.schedule.properties.date.type, 'string');
});
