/**
 * 拼出完整的生图提示词。
 *
 * @param {object} o
 * @param {'avatar'|'chat'|'qzone'} o.scene  哪个入口（决定用途那段怎么说）
 * @param {string[]} [o.context]  这个入口独有的上下文（心情、说说原文……）排在用途前面
 * @param {boolean} [o.wantParseFormat]  要不要她按三行回（qzone/avatar 要，chat 不用）
 * @returns {string}
 */
export function buildDrawPrompt({ scene = 'chat', context = [], wantParseFormat = false } = {}) {
  const L = []
  // ① 各入口独有的上下文（心情/经历/说说原文……）
  for (const line of context) if (line) L.push(line)
  if (context.length) L.push('')
  // ② 用途 —— 永远排在三步走前面
  for (const line of (PURPOSE[scene] || PURPOSE.chat)) L.push(line)
  L.push('', '---', '')
  // ③ 三步走（四个入口完全一样）
  for (const line of STEP12) L.push(line)
  L.push('')
  for (const line of STEP3) L.push(line)
  L.push('')
  // ④ 关键特征 + 收尾
  for (const line of TAIL) L.push(line)
  // ⑤ 要她按三行回时，给出格式
  if (wantParseFormat) {
    L.push('', '**最后按这个格式回三行：**',
      '这张画：有我自己       （或者：这张画：没有我自己）',
      '参考图：self:2          （只有画自己才写这行）',
      '画面：<你那一段描述>')
  }
  return L.join(String.fromCharCode(10))
}

/**
 * 解析她回的三行。四个入口共用同一个解析 —— 以前每个入口各写一份正则。
 *   「这张画：有我自己」   → hasSelf: true
 *   「参考图：self:3」     → ref: 'self:3'
 *   「画面：…」            → prompt: '…'
 * 没按格式回（只有一段描述）→ hasSelf: false，ref: null，prompt 原样 —— 不乱猜。
 */
export function parseDrawAnswer(text) {
  const raw = String(text || '').trim().replace(/^[「『"\'“”]+|[」』"\'“”]+$/g, '')
  if (!raw) return { hasSelf: false, ref: null, prompt: '' }
  const lineSelf = /这张画\s*[:：]\s*(有|没有)\s*我自己/.exec(raw)
  // 【修 2026-11-25 · 测试抓到的】原来写成 (…|我|我自己|自己)，
  // 正则是「先匹配到就停」，所以「参考图：我自己」会被截成「我」。
  // 虽然下游 resolveDrawImage 也认「我」，但返回值不该跟原文对不上 —— 长选项必须排前面。
  const refMatch = /参考图\s*[:：]\s*(self(?::\d{1,2})?|三视图(?::\d{1,2})?|我自己|自己|我)/i.exec(raw)
  const linePrompt = /画面\s*[:：]\s*([\s\S]+)/.exec(raw)
  const hasSelf = lineSelf ? lineSelf[1] === '有' : /参考图\s*[:：]/.test(raw)
  const ref = hasSelf && refMatch ? refMatch[1] : null
  const body = (linePrompt ? linePrompt[1] : raw)
    .replace(/这张画\s*[:：]\s*(有|没有)\s*我自己/g, '')
    .replace(/参考图\s*[:：]\s*\S+/g, '')
    .trim()
  return { hasSelf, ref, prompt: body.slice(0, 400) }
}
