// 时间格式 HH:MM；结束 < 开始表示跨午夜（夜班 23:00-07:00 这种）。

// 周序号锚点：2024-01-01 是周一。轮班职业用它算「这周轮到哪套班」。
export const WEEK_ANCHOR = new Date(2024, 0, 1).getTime()
const WEEK_MS = 7 * 24 * 60 * 60 * 1000
export function weekIdxOf(t) {
  const d = new Date(t)
  const day = new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime()
  return Math.floor((day - WEEK_ANCHOR) / WEEK_MS)
}

