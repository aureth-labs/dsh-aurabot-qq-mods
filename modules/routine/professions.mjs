// 销售员卖什么：按 dayKey 稳定哈希挑一个——同一天说法一致，隔天可能换货
export function goodsOf(prof, day) {
  if (!prof || !Array.isArray(prof.goods) || !prof.goods.length) return ''
  let h = 0
  for (const ch of String(day)) h = (h * 31 + ch.charCodeAt(0)) >>> 0
  return prof.goods[h % prof.goods.length]
}
